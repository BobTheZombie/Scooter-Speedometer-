-- RiderLink+ v8.6 founder-code and membership entitlements.
-- Run once in the Supabase SQL editor. Safe to run again.
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.riderlink_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.riderlink_invite_codes (
  id uuid primary key default extensions.gen_random_uuid(),
  code_hash text not null unique,
  recipient_name text not null check (char_length(recipient_name) between 1 and 80),
  reward_type text not null check (reward_type in ('developer_lifetime','founder_lifetime','founder_price','complimentary')),
  complimentary_days integer check (complimentary_days between 1 and 3650),
  max_redemptions integer not null default 1 check (max_redemptions between 1 and 1000),
  redemption_count integer not null default 0 check (redemption_count >= 0),
  expires_at timestamptz,
  revoked boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.riderlink_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  tier text not null check (tier in ('developer','founder_lifetime','founder_price','complimentary')),
  plus_access boolean not null default false,
  founder_price_eligible boolean not null default false,
  expires_at timestamptz,
  source_code_id uuid references public.riderlink_invite_codes(id) on delete set null,
  granted_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.riderlink_redemptions (
  id bigint generated by default as identity primary key,
  code_id uuid not null references public.riderlink_invite_codes(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  redeemed_at timestamptz not null default now(),
  unique(code_id,user_id)
);

alter table public.riderlink_admins enable row level security;
alter table public.riderlink_invite_codes enable row level security;
alter table public.riderlink_entitlements enable row level security;
alter table public.riderlink_redemptions enable row level security;

drop policy if exists "members read own entitlement" on public.riderlink_entitlements;
create policy "members read own entitlement" on public.riderlink_entitlements
for select to authenticated using (user_id=auth.uid());

